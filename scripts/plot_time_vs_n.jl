# fig[0, 1:end] = legend

plotfile =
    joinpath("figures", basename(@__FILE__) * begin
        if nameof(Makie.current_backend()) === :CairoMakie
            ".pdf"
        else
            ".png"
        end
    end
    )
save(plotfile, fig)
@info "saved `fig` to $(plotfile)"
fig

